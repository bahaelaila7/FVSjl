# EM habitat IEMTYP → the two candidate fuel models (em/fmcba.f ENTRY EMMD). Clamped to [1,122].
@inline function em_md_models(iemtyp::Int)::NTuple{2,Int}
    i = (iemtyp < 1 || iemtyp > 122) ? 1 : iemtyp
    return (_EM_MD1[i], _EM_MD2[i])
end

@inline function em_live_fuel_loading(covtyp::Int, percov::Float32)::NTuple{2,Float32}
    (covtyp < 1 || covtyp > 19) && (covtyp = 3)
    herb  = _cr_algslp2(percov, 10f0, 60f0, _EM_FULIVI[covtyp, 1], _EM_FULIVE[covtyp, 1])
    shrub = _cr_algslp2(percov, 10f0, 60f0, _EM_FULIVI[covtyp, 2], _EM_FULIVE[covtyp, 2])
    return (herb, shrub)
end

function em_dead_fuel_loading(covtyp::Int, percov::Float32)::Vector{Float32}
    (covtyp < 1 || covtyp > 19) && (covtyp = 3)
    out = Vector{Float32}(undef, 11)
    @inbounds for isz in 1:11
        out[isz] = _cr_algslp2(percov, 10f0, 60f0, _EM_FUINII[covtyp, isz], _EM_FUINIE[covtyp, isz])
    end
    return out
end
