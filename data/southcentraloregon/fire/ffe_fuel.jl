# so/fmcba.f — resolve the (herb, shrub) live pool + the 11-class STFUEL dead pool from COVTYP/ISSX/logmod.
# `logmod` is ILOGMOD (1 = no-apparent-logging default; 2 when FMSSTAGE returned 0 → bare/SI). Returns
# (flive1, flive2, stfuel::NTuple{11,Float32}); all zero when no COVRINI/FUELINI match (fmcba.f IPOSN=0).
function so_fuel_ini(covtyp::Int, issx::Int, logmod::Int)
    z11 = (0f0,0f0,0f0,0f0,0f0,0f0,0f0,0f0,0f0,0f0,0f0)
    ispx = covtyp == 2 ? 1 : covtyp          # sugar pine (2) uses white pine (1) fuels
    key = ispx * 10 + issx
    covr = get(SO_COVRINI, key, nothing)
    covr === nothing && return (0f0, 0f0, z11)
    imodx = covr[clamp(logmod, 1, 5)]        # COVRINI(ILOGMOD+1, I)
    imodx <= 0 && return (0f0, 0f0, z11)
    fu = get(SO_FUELINI, imodx, nothing)
    fu === nothing && return (0f0, 0f0, z11)
    # fu = (herb, shrub, <.25, .25-1, 1-3, 3-9, 9-20, 20-35, 35-50, >50, litter, duff) = FUELINI(2:13)
    flive1 = fu[1]; flive2 = fu[2]
    stfuel = (
        fu[3],                               # 1  <0.25
        fu[4],                               # 2  0.25-1
        fu[5],                               # 3  1-3
        fu[6] * (2f0/3f0),                   # 4  3-6  = FUELINI(7)·2/3
        fu[6] * (1f0/3f0) + fu[7] * (3f0/11f0),  # 5  6-12 = FUELINI(7)/3 + FUELINI(8)·3/11
        fu[7] * (8f0/11f0) + fu[8],          # 6  12-20 = FUELINI(8)·8/11 + FUELINI(9)
        0f0,                                 # 7  20-35 (fmcba.f:718 forces 0)
        fu[9],                               # 8  35-50 = FUELINI(10)
        fu[10],                              # 9  >50   = FUELINI(11)
        fu[11],                              # 10 litter= FUELINI(12)
        fu[12],                              # 11 duff  = FUELINI(13)
    )
    return (flive1, flive2, stfuel)
end
