# PVREF4 lookup structures: the first full (PVCODE, PVREF) match (the DO loop EXITs there) and the code / ref sets
# the loop's LPVCOD / LPVREF flags come from when no row matches both.
const CI_PVREF4_MAP = let d = Dict{Tuple{String,String},String}()
    for (c, r, h) in CI_PVREF4; haskey(d, (c, r)) || (d[(c, r)] = h); end
    d
end
const CI_PVREF4_CODES = Set(t[1] for t in CI_PVREF4)
const CI_PVREF4_REFS = Set(t[2] for t in CI_PVREF4)

"""
    ci_habitat_kodtyp(kard2, cpvref, kodtyp) -> (kodtyp, errs, lpvxxx)

ci/habtyp.f:44-75 up to the ICITYP search: with a PV reference code (CPVREF non-blank) PVREF4 crosswalks
(KARD2 = the PV_CODE text, CPVREF) → KODTYP = HABPVR (0 when no row matches both), and the LPVCOD/LPVREF branches
raise FVS34 / FVS33+FVS32 / FVS32 / FVS33 and set LPVXXX (⇒ the grinit ICINDX=21 / ITYPE=4 default stays).
Without a reference code KODTYP is the caller's IFIX(ARRAY2). A KODTYP outside 10..999 without LPVXXX is FVS14.
`errs` lists the ERRGRO numbers in call order.
"""
function ci_habitat_kodtyp(kard2::AbstractString, cpvref::AbstractString, kodtyp::Integer)
    errs = Int[]; lpvxxx = false; kod = Int(kodtyp)
    k = String(strip(kard2)); r = String(strip(cpvref))
    if !isempty(r)
        h = get(CI_PVREF4_MAP, (k, r), nothing)
        if h !== nothing
            kod = something(tryparse(Int, strip(h)), 0); lc = true; lr = true
        else
            kod = 0; lc = k in CI_PVREF4_CODES; lr = r in CI_PVREF4_REFS
        end
        if lc && lr && (kod < 10 || kod > 999)
            push!(errs, 34); lpvxxx = true
        elseif !lc && !lr
            push!(errs, 33, 32); lpvxxx = true
        elseif !lr && lc
            push!(errs, 32); lpvxxx = true
        elseif !lc && lr
            push!(errs, 33); lpvxxx = true
        end
    end
    (kod < 10 || kod > 999) && !lpvxxx && push!(errs, 14)
    return (kod, errs, lpvxxx)
end
