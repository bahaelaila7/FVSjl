"""
    r4_habitat_itype(kard2, cpvref, array2) -> (itype, errs)

tt/habtyp.f (= ut/habtyp.f) :152-228 for a habitat code KARD2 (the PV_CODE text), CPVREF (blank = "") and the
numeric ARRAY2 = IFIX(PV_CODE). A code of ≥ 2 characters with a reference code goes through PVREF4 (KARD2 := the
matched HABPVR or blank, ARRAY2 := F4.0 of it; FVS34 / FVS33+FVS32 / FVS32 / FVS33 ⇒ LPVXXX), then CRDECD matches
KARD2 against R4HABT (KODTYP = ITYPE = the index, 0 when unmatched). No match ⇒ the sequence-number fallback
IHB = IFIX(ARRAY2) when IHB ≤ NR4. Still 0 and not LPVXXX ⇒ FVS14. `errs` = the ERRGRO numbers in call order.
"""
function r4_habitat_itype(kard2::AbstractString, cpvref::AbstractString, array2::Real)
    errs = Int[]; lpvxxx = false
    k = String(strip(kard2)); r = String(strip(cpvref)); a2 = Float64(array2)
    kod = 0
    if length(k) >= 2
        if !isempty(r)
            h = get(R4_PVREF4_MAP, (k, r), nothing)
            if h === nothing
                k = ""; a2 = 0.0; lc = String(strip(kard2)) in R4_PVREF4_CODES; lr = r in R4_PVREF4_REFS
            else
                k = String(strip(h)); a2 = _f40(h); lc = true; lr = true
            end
            if lc && lr && isempty(k)
                push!(errs, 34); lpvxxx = true
            elseif !lc && !lr
                push!(errs, 33, 32); lpvxxx = true
            elseif !lr && lc
                push!(errs, 32); lpvxxx = true
            elseif !lc && lr
                push!(errs, 33); lpvxxx = true
            end
        end
        if !isempty(k)                                               # CRDECD: first 8 chars, upper-cased, text match
            idx = findfirst(==(uppercase(first(k, 8))), R4_HABT_TEXT)
            kod = idx === nothing ? 0 : Int(idx)
        end
    end
    if kod == 0
        ihb = trunc(Int, a2)
        ihb <= length(R4_HABT_TEXT) && (kod = ihb)                 # IF(IHB.LE.NR4) KODTYP=ITYPE=IHB
    end
    kod <= 0 && !lpvxxx && push!(errs, 14)
    return (max(kod, 0), errs)
end
